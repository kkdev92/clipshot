/**
 * Create a PNG buffer with specific dimensions
 * Note: This creates a minimal PNG structure, not a fully valid one for rendering
 */
export function createPngWithDimensions(width: number, height: number): Buffer {
  const widthBytes = Buffer.alloc(4);
  widthBytes.writeUInt32BE(width, 0);

  const heightBytes = Buffer.alloc(4);
  heightBytes.writeUInt32BE(height, 0);

  return Buffer.concat([
    // PNG Signature
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    // IHDR chunk length
    Buffer.from([0x00, 0x00, 0x00, 0x0d]),
    // IHDR type
    Buffer.from([0x49, 0x48, 0x44, 0x52]),
    // Width
    widthBytes,
    // Height
    heightBytes,
    // bit depth, color type, compression, filter, interlace
    Buffer.from([0x08, 0x06, 0x00, 0x00, 0x00]),
    // CRC (placeholder)
    Buffer.from([0x00, 0x00, 0x00, 0x00]),
    // IEND chunk
    Buffer.from([0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82]),
  ]);
}

/**
 * Create a buffer of specified size (for size limit tests)
 * Fills with PNG-like header to pass validation
 */
export function createLargeBuffer(sizeBytes: number): Buffer {
  const buffer = Buffer.alloc(sizeBytes);
  // Copy PNG signature to make it look like a valid PNG
  VALID_PNG_BUFFER.copy(buffer, 0, 0, Math.min(VALID_PNG_BUFFER.length, sizeBytes));
  return buffer;
}

/**
 * Create a buffer of specified size in MB
 */
export function createLargeBufferMB(sizeMB: number): Buffer {
  return createLargeBuffer(sizeMB * 1024 * 1024);
}

